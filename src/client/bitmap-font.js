/**
 * Get tile ID for a character
 * @param {string} char - Single character
 * @returns {number} Tile ID (0x100 + ASCII code)
 */
export function charToTileId(char) {
  return FONT_TILE_BASE + char.charCodeAt(0);
}

/**
 * Get character from tile ID
 * @param {number} tileId - Tile ID
 * @returns {string|null} Character or null if not a font tile
 */
export function tileIdToChar(tileId) {
  if (tileId < FONT_TILE_BASE) return null;
  return String.fromCharCode(tileId - FONT_TILE_BASE);
}

/**
 * Convert bitmap font character to hex sprite format
 * @param {number[]} charData - 8 bytes of bitmap data
 * @param {number} colorIndex - Palette index to use for foreground
 * @returns {string[]} Array of 8 hex strings (8 characters each)
 */
export function fontCharToHexSprite(charData, colorIndex = 1) {
  const hexRows = [];
  for (let row = 0; row < 8; row++) {
    const rowData = charData[row];
    let hexRow = '';
    for (let col = 0; col < 8; col++) {
      const bit = (rowData >> (7 - col)) & 1;
      hexRow += bit ? colorIndex.toString(16) : '0';
    }
    hexRows.push(hexRow);
  }
  return hexRows;
}

/**
 * Generate all font tile sprites for pre-rendering
 * @param {number} colorIndex - Palette index to use for foreground (default 1)
 * @returns {Array<{tileId: number, sprite: string[]}>} Array of font tile sprites
 */
export function generateFontTileSprites(colorIndex = 1) {
  const fontSprites = [];

  Object.entries(BITMAP_FONT).forEach(([char, charData]) => {
    const tileId = charToTileId(char);
    fontSprites.push({
      tileId: tileId,
      sprite: fontCharToHexSprite(charData, colorIndex)
    });
  });

  return fontSprites;
}

/**
 * Renders bitmap text directly to a canvas context
 * @param {CanvasRenderingContext2D} ctx - Canvas context
 * @param {string} text - Text to render
 * @param {number} x - X position
 * @param {number} y - Y position
 * @param {string} color - CSS color string (e.g., '#FFFFFF')
 * @param {number} scale - Scale factor (1 = 8x8, 2 = 16x16, etc.)
 */
export function renderBitmapText(ctx, text, x, y, color = '#FFFFFF', scale = 1) {
  const charWidth = 8 * scale;
  const charHeight = 8 * scale;

  for (let i = 0; i < text.length; i++) {
    const char = text[i].toUpperCase();
    const charData = BITMAP_FONT[char];

    if (!charData) {
      // Unknown character, skip
      continue;
    }

    const charX = x + (i * charWidth);

    // Render each row of the character
    for (let row = 0; row < 8; row++) {
      const rowData = charData[row];

      // Render each pixel in the row
      for (let col = 0; col < 8; col++) {
        const bit = (rowData >> (7 - col)) & 1;

        if (bit) {
          ctx.fillStyle = color;
          ctx.fillRect(
            charX + (col * scale),
            y + (row * scale),
            scale,
            scale
          );
        }
      }
    }
  }
}

/**
 * Calculates the width of text in pixels
 * @param {string} text - Text to measure
 * @param {number} scale - Scale factor
 * @returns {number} Width in pixels
 */
export function measureBitmapText(text, scale = 1) {
  return text.length * 8 * scale;
}

/**
 * Renders centered bitmap text
 * @param {CanvasRenderingContext2D} ctx - Canvas context
 * @param {string} text - Text to render
 * @param {number} centerX - Center X position
 * @param {number} y - Y position
 * @param {string} color - CSS color string
 * @param {number} scale - Scale factor
 */
export function renderCenteredBitmapText(ctx, text, centerX, y, color = '#FFFFFF', scale = 1) {
  const textWidth = measureBitmapText(text, scale);
  const x = centerX - (textWidth / 2);
  renderBitmapText(ctx, text, x, y, color, scale);
}